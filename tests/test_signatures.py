"""The table of the signatures of the WASI imports (fusedwasi.signatures) and how it relates to the Python and C twins.

The table is generated by tools/make_signatures.py from the official witx / WIT kept in tools/spec_sources/. These tests prove that
(1) the committed files are what the generator writes (no drift, offline), (2) the twins and the table have the same functions, the differences
being listed below with a reason, (3) every function has the same number of parameters in the table, in Python and in C (the names may differ and
are reported in docs/signatures.md, not changed), (4) the generated stubs are valid for ruff and pyright and behave as Protocols should.
"""

