P2_PACKAGES = ("cli", "clocks", "filesystem", "http", "io", "random", "sockets")

# ---- what the repository does not have, and why ---------------------------------------------------------------------------------

# Functions of the table of 0.2 that the twins do not implement. All three are behind an `@unstable` feature in the WIT of 0.2.12 and are
# left out on purpose (host_scope.md: "without the unstable items"); `network-error-code`, the fourth unstable one, is implemented.
P2_NOT_IMPLEMENTED = {
    ("wasi:clocks/timezone@0.2.12", "display"): "unstable (feature clocks-timezone); no time zones in the host",
    ("wasi:clocks/timezone@0.2.12", "utc-offset"): "unstable (feature clocks-timezone); no time zones in the host",
    (
        "wasi:http/types@0.2.12",
        "[method]response-outparam.send-informational",
    ): "unstable (feature informational-outbound-responses); named as not done in host_scope.md",
}


def load_generator() -> ModuleType:
    spec = importlib.util.spec_from_file_location("make_signatures", GENERATOR)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules["make_signatures"] = module
    spec.loader.exec_module(module)
    return module


def impl_name(f: Function) -> str:
    """The name of the function of 0.2 in the twins: wasi_<package>_<interface>[_<resource>]_<function>."""
    assert f.package is not None and f.interface is not None
    last = {"constructor": "new", "resource-drop": "drop"}.get(f.kind or "", f.official_name)
    parts = ["wasi", f.package.split(":")[1], f.interface, f.resource or "", last]
    return "_".join(p.replace("-", "_") for p in parts if p)


def c_params(text: str) -> list[str]:
    return [p.strip() for p in text.split(",") if p.strip()]


def p1_c_functions() -> tuple[dict[str, list[str]], dict[str, list[str]]]:
    """(wasi_snapshot_preview1 entry points, wasi_unstable entry points) of the C headers: name to the parameters after the guest `fusedwasi_p2_guest *g`."""
    found: dict[str, list[str]] = {}
    for header in sorted((C_INCLUDE / "p1").glob("*.h")):
        text = header.read_text(encoding="utf-8")
        for m in re.finditer(
            r"FUSEDWASI_P1_FN\s+(?:uint32_t|void)\s+fusedwasi_p1_(\w+)\(\s*fusedwasi_p2_guest\s*\*g\s*(?:,([^)]*?))?\)",
            text,
            re.DOTALL,
        ):
            found[m.group(1)] = c_params(m.group(2) or "")
    unstable = {k.removeprefix("unstable_"): v for k, v in found.items() if k.startswith("unstable_")}
    return {k: v for k, v in found.items() if not k.startswith("unstable_")}, unstable


def p2_c_functions() -> dict[str, list[str]]:
    found: dict[str, list[str]] = {}
    for pkg in P2_PACKAGES:
        text = (C_INCLUDE / "p2" / f"wasi_p2_{pkg}.h").read_text(encoding="utf-8")
        for m in re.finditer(r"FUSEDWASI_P2_FN\s+[\w\s*]+?\bfusedwasi_(wasi_\w+)\(([^)]*)\)", text):
            found[m.group(1)] = c_params(m.group(2))
    return found


def p2_python_functions() -> dict[str, Any]:
    found: dict[str, Any] = {}
    for pkg in P2_PACKAGES:
        module = importlib.import_module(f"fusedwasi.p2.wasi_p2_{pkg}")
        for name, fn in vars(module).items():
            if inspect.isfunction(fn) and name.startswith("wasi_") and fn.__module__ == module.__name__:
                found[name] = fn
    return found


