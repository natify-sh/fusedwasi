def test_regenerating_gives_the_committed_files() -> None:
    if not GENERATOR.is_file():
        pytest.skip("tools/ is not part of this checkout")
    generated: dict[str, bytes] = load_generator().generate()
    assert sorted(generated) == ["wasi_p1.json", "wasi_p1_protocols.pyi", "wasi_p2.json", "wasi_p2_protocols.pyi"]
    for name, data in generated.items():
        assert (SIGS / name).read_bytes() == data, (
            f"{name} differs from the generator: run `python tools/make_signatures.py`"
        )


def test_the_sources_are_the_ones_the_header_names() -> None:
    sources = REPO / "tools" / "spec_sources"
    if not sources.is_dir():
        pytest.skip("tools/ is not part of this checkout")
    import hashlib

    for key, tag in (("p1", "v0.2.9"), ("p2", "v0.2.12")):
        header = json.loads((SIGS / f"wasi_{key}.json").read_text(encoding="utf-8"))["source"]
        assert header["tag"] == tag
        assert re.fullmatch(r"[0-9a-f]{40}", header["commit"])
        assert header["files"]
        for record in header["files"]:
            assert hashlib.sha256((sources / record["path"]).read_bytes()).hexdigest() == record["sha256"], record[
                "path"
            ]


