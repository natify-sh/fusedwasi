def test_p1_python_has_the_functions_of_the_table() -> None:
    table = {f.name: f for f in signatures.load("p1").functions}
    public = {
        n
        for n, f in vars(wasi_p1).items()
        if inspect.isfunction(f) and not n.startswith("_") and f.__module__ == wasi_p1.__name__
    }
    assert public - set(table) == set()  # the helpers of the module (`_filestat_of_fd`, ...) start with an underscore
    assert set(table) - public == set()
    for name, f in table.items():
        params = list(inspect.signature(getattr(wasi_p1, name)).parameters)
        assert params[0] == "guest"
        assert len(params) - 1 == len(f.params), f"wasi_p1.{name}: python {len(params) - 1}, table {len(f.params)}"


def test_p1_unstable_python_functions_are_in_the_table() -> None:
    table = {f.name: f for f in signatures.load("p1").functions}
    public = {
        n
        for n, f in vars(wasi_p1_unstable).items()
        if inspect.isfunction(f)
        and not n.startswith("_")
        and f.__module__ in (wasi_p1.__name__, wasi_p1_unstable.__name__)
    }
    assert public - set(table) == set()
    assert set(table) - public == {"sock_accept"}  # not a call of the first snapshot (the module says so)
    for name in public:
        params = list(inspect.signature(getattr(wasi_p1_unstable, name)).parameters)
        assert len(params) - 1 == len(table[name].params), name


def test_p1_c_has_the_functions_of_the_table() -> None:
    table = {f.name: f for f in signatures.load("p1").functions}
    current, unstable = p1_c_functions()
    assert set(current) == set(table)
    for name, params in current.items():
        assert len(params) == len(table[name].params), (
            f"fusedwasi_p1_{name}: c {len(params)}, table {len(table[name].params)}"
        )
    assert set(unstable) <= set(table)
    assert set(unstable) == {"fd_seek", "fd_fdstat_get", "fd_filestat_get", "path_filestat_get", "poll_oneoff"}
    for name, params in unstable.items():
        assert len(params) == len(table[name].params), f"fusedwasi_p1_unstable_{name}"


def test_p2_python_has_the_functions_of_the_table() -> None:
    table = {impl_name(f): f for f in signatures.load("p2").functions}
    assert len(table) == 204  # the mapping is one to one
    python = p2_python_functions()
    assert set(python) - set(table) == set()
    missing = {(table[n].module, table[n].name) for n in set(table) - set(python)}
    assert missing == set(P2_NOT_IMPLEMENTED)
    for key in missing:
        f = signatures.load("p2").get(*key)
        assert f is not None and f.stability == "unstable", key
    for name, fn in python.items():
        params = [
            p for p in inspect.signature(fn).parameters if p != "comp"
        ]  # `comp` is the component of the call, not a parameter of the import
        assert len(params) - 1 == len(table[name].params), (
            f"{name}: python {len(params) - 1}, table {len(table[name].params)}"
        )


def test_p2_c_has_the_functions_of_the_table() -> None:
    table = {impl_name(f): f for f in signatures.load("p2").functions}
    c = p2_c_functions()
    assert set(c) - set(table) == set()
    assert {(table[n].module, table[n].name) for n in set(table) - set(c)} == set(P2_NOT_IMPLEMENTED)
    for name, params in c.items():
        wasm = [p for p in params if not re.search(r"\bcomp\b", p)]
        assert len(wasm) - 1 == len(table[name].params), f"{name}: c {len(wasm) - 1}, table {len(table[name].params)}"


def test_the_table_says_where_each_function_is_and_whether_it_takes_comp() -> None:
    """`c_name`, `python_module`, `python_name` and `takes_comp` of the table agree with what the headers and the Python files have, read here by other means than the generator."""
    c1, _ = p1_c_functions()
    c2 = p2_c_functions()
    python2 = p2_python_functions()
    for f in signatures.load("p1").functions:
        assert (f.c_name, f.python_module, f.python_name, f.takes_comp) == (
            f"fusedwasi_p1_{f.name}",
            "fusedwasi.p1.wasi_p1",
            f.name,
            False,
        )
        assert f.name in c1 and getattr(wasi_p1, f.name) is f.python_function()
    left_out: set[tuple[str, str]] = set()
    for f in signatures.load("p2").functions:
        if f.key in P2_NOT_IMPLEMENTED:
            assert (f.c_name, f.python_module, f.python_name, f.takes_comp) == (None, None, None, None)
            with pytest.raises(LookupError):
                f.python_function()
            left_out.add(f.key)
            continue
        name = impl_name(f)
        assert f.c_name == "fusedwasi_" + name and f.python_name == name and f.python_module is not None
        assert f.python_module.startswith("fusedwasi.p2.wasi_p2_")
        assert f.python_function() is python2[name]
        in_c = any(re.search(r"\bcomp\b", p) for p in c2[name])
        in_python = "comp" in inspect.signature(python2[name]).parameters
        assert f.takes_comp is in_c is in_python, name
    assert left_out == set(P2_NOT_IMPLEMENTED)


