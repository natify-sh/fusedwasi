def test_known_signatures() -> None:
    p1, p2 = signatures.load("p1"), signatures.load("p2")

    def shape(f: Function | None) -> tuple[list[str], list[str]]:
        assert f is not None
        return [p.type for p in f.params], [p.type for p in f.results]

    m = "wasi_snapshot_preview1"
    assert shape(p1.get(m, "fd_read")) == (["i32"] * 4, ["i32"])
    assert shape(p1.get(m, "fd_seek")) == (["i32", "i64", "i32", "i32"], ["i32"])
    assert shape(p1.get(m, "clock_time_get")) == (["i32", "i64", "i32"], ["i32"])
    assert shape(p1.get(m, "path_open")) == (["i32"] * 5 + ["i64", "i64", "i32", "i32"], ["i32"])
    assert shape(p1.get(m, "proc_exit")) == (["i32"], [])
    assert [p.name for p in (p1.get(m, "poll_oneoff") or p1.functions[0]).params] == [
        "in",
        "out",
        "nsubscriptions",
        "retptr",
    ]
    roles = [p.role for p in (p1.get(m, "fd_write") or p1.functions[0]).params]
    assert roles == ["handle", "pointer", "length", "retptr"]

    assert shape(p2.get("wasi:clocks/monotonic-clock@0.2.12", "now")) == ([], ["i64"])
    assert shape(p2.get("wasi:clocks/wall-clock@0.2.12", "now")) == (
        ["i32"],
        [],
    )  # a record of two values: through retptr
    assert shape(p2.get("wasi:io/streams@0.2.12", "[method]output-stream.blocking-write-and-flush")) == (
        ["i32"] * 4,
        [],
    )
    assert shape(p2.get("wasi:io/streams@0.2.12", "[resource-drop]output-stream")) == (["i32"], [])
    assert shape(p2.get("wasi:cli/stdout@0.2.12", "get-stdout")) == ([], ["i32"])
    assert shape(p2.get("wasi:http/types@0.2.12", "[constructor]fields")) == ([], ["i32"])
    # 15 flat parameters: self, network, a variant of two socket addresses (tag and eleven joined values) and the result pointer
    assert len(p2.get("wasi:sockets/tcp@0.2.12", "[method]tcp-socket.start-bind").params) == 15  # type: ignore[union-attr]


