@pytest.mark.parametrize("snapshot", ["p1", "p2"])
def test_the_stubs_parse_and_have_one_protocol_for_each_function(snapshot: str) -> None:
    text = (SIGS / f"wasi_{snapshot}_protocols.pyi").read_text(encoding="utf-8")
    tree = ast.parse(text)
    imports = [n for n in tree.body if isinstance(n, (ast.Import, ast.ImportFrom))]
    assert [ast.unparse(n) for n in imports] == ["from typing import Protocol"]  # a stub is copied: it must stand alone
    assert "fusedwasi" not in "\n".join(ast.unparse(n) for n in imports)
    classes = [n for n in tree.body if isinstance(n, ast.ClassDef)]
    functions = signatures.load(snapshot).functions  # type: ignore[arg-type]
    assert [c.name for c in classes] == [f.protocol for f in functions]
    for c, f in zip(classes, functions, strict=True):
        assert [ast.unparse(b) for b in c.bases] == ["Protocol"]
        (call,) = [n for n in c.body if isinstance(n, ast.FunctionDef)]
        assert call.name == "__call__"
        assert [a.arg for a in [*call.args.posonlyargs, *call.args.args]] == [
            "self",
            *[escaped(p.name) for p in f.params],
        ]
        assert not call.args.kwonlyargs and (
            len(call.args.posonlyargs) == 1 + len(f.params) if f.params else not call.args.posonlyargs
        )
        assert ast.get_docstring(c)
        assert ast.unparse(call.returns or ast.Constant(None)) == (
            "None" if not f.results else "float" if f.results[0].type in ("f32", "f64") else "int"
        )  # type: ignore[arg-type]


def test_python_names_are_valid_identifiers() -> None:
    for snapshot in ("p1", "p2"):
        tree = ast.parse((SIGS / f"wasi_{snapshot}_protocols.pyi").read_text(encoding="utf-8"))
        for node in ast.walk(tree):
            if isinstance(node, ast.arg):
                assert node.arg.isidentifier() and not keyword.iskeyword(node.arg), node.arg
    text = (SIGS / "wasi_p1_protocols.pyi").read_text(encoding="utf-8")
    assert "class PollOneoff(Protocol):" in text and "in_: int" in text
    assert "self_: int" in (SIGS / "wasi_p2_protocols.pyi").read_text(encoding="utf-8")


def escaped(name: str) -> str:
    return name + "_" if keyword.iskeyword(name) or name == "self" else name


def find_tool(name: str) -> list[str] | None:
    sibling = Path(sys.executable).parent / name
    if sibling.is_file():
        return [str(sibling)]
    found = shutil.which(name)
    return [found] if found else None


