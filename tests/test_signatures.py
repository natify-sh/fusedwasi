SAMPLE = """\
from wasi_p1_protocols import FdWrite, ProcExit
from wasi_p2_protocols import CliExitExit, FilesystemTypesDescriptorReadViaStream, IoStreamsInputStreamRead


def with_other_names(file: int, parts: int, count: int, out: int) -> int:
    return 0


def with_the_wrong_arity(file: int, parts: int) -> int:
    return 0


def no_result(code: int) -> None:
    return None


def method(handle: int, start: int, ret: int) -> None:
    return None


def read(stream: int, n: int, ret: int) -> None:
    return None


ok_other_names: FdWrite = with_other_names
ok_no_result: ProcExit = no_result
ok_p2_method: FilesystemTypesDescriptorReadViaStream = method
ok_p2_read: IoStreamsInputStreamRead = read
ok_p2_exit: CliExitExit = no_result
bad_arity: FdWrite = with_the_wrong_arity  # expected: error
bad_result: ProcExit = with_other_names  # expected: error
same_arity: FilesystemTypesDescriptorReadViaStream = read  # fine: the same number of parameters, the names do not matter
bad_p2: CliExitExit = method  # expected: error
"""


def test_a_protocol_accepts_other_names_and_rejects_the_wrong_arity(tmp_path: Path) -> None:
    pyright = find_tool("pyright")
    if pyright is None:
        pytest.skip("pyright is not installed (it is a dev dependency of the project)")
    for s in ("p1", "p2"):
        shutil.copy(SIGS / f"wasi_{s}_protocols.pyi", tmp_path / f"wasi_{s}_protocols.pyi")
    (tmp_path / "sample.py").write_text(SAMPLE, encoding="utf-8")
    (tmp_path / "pyrightconfig.json").write_text(
        json.dumps({"typeCheckingMode": "strict", "pythonVersion": "3.11"}), encoding="utf-8"
    )
    run = subprocess.run(
        [*pyright, "--outputjson", "-p", str(tmp_path)],
        capture_output=True,
        text=True,
        cwd=tmp_path,
        timeout=600,
        check=False,
    )
    try:
        report = json.loads(run.stdout)
    except json.JSONDecodeError:
        pytest.skip(f"pyright could not run here: {run.stdout[-300:]} {run.stderr[-300:]}")
    errors = [d for d in report["generalDiagnostics"] if d["severity"] == "error"]
    in_stubs = [d for d in errors if not d["file"].endswith("sample.py")]
    assert in_stubs == [], in_stubs  # strict, as the repository configures pyright
    lines = SAMPLE.splitlines()
    expected = {i + 1 for i, line in enumerate(lines) if line.endswith("# expected: error")}
    got = {d["range"]["start"]["line"] + 1 for d in errors if d["file"].endswith("sample.py")}
    assert expected and got == expected, [d["message"] for d in errors]
