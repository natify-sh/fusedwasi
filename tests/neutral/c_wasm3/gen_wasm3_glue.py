"""Writes the C glue between wasm3 and the functions of fusedwasi: one wasm3 raw function for each import of WASI 0.1 and 0.2, and the two tables that the driver links from.

    python gen_wasm3_glue.py OUTPUT.h

What it reads is public: the table of the signatures (`fusedwasi.signatures`: the module, the name and the flat parameters and results of every import) and the C headers (`fusedwasi.get_include()`),
from which it takes the prototype of each function, because the table does not say whether a function of 0.2 takes the number of the memory (`comp`) and the name of the C function is a rule
that is not written down (`fusedwasi_` + `wasi_<package>_<interface>[_<resource>]_<function>`).
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import fusedwasi
from fusedwasi import signatures

INCLUDE = Path(fusedwasi.get_include()) / "fusedwasi"
WIDTH = {"i32": ("uint32_t", "i"), "i64": ("uint64_t", "I")}
P2_PACKAGES = ("cli", "clocks", "filesystem", "http", "io", "random", "sockets")


def c_name(function: signatures.Function) -> str:
    assert function.package is not None and function.interface is not None
    last = {"constructor": "new", "resource-drop": "drop"}.get(function.kind or "", function.official_name)
    parts = ["wasi", function.package.split(":")[1], function.interface, function.resource or "", last]
    return "fusedwasi_" + "_".join(p.replace("-", "_") for p in parts if p)


def p2_prototypes() -> dict[str, tuple[str, int]]:
    """name to (the type it returns, the number of parameters after the guest) for every function of the headers of 0.2."""
    found: dict[str, tuple[str, int]] = {}
    for package in P2_PACKAGES:
        text = (INCLUDE / "p2" / f"wasi_p2_{package}.h").read_text(encoding="utf-8")
        for m in re.finditer(r"FUSEDWASI_P2_FN\s+(\w+)\s+(fusedwasi_wasi_\w+)\(([^)]*)\)", text):
            found[m.group(2)] = (m.group(1), len([p for p in m.group(3).split(",") if p.strip()]) - 1)
    return found


def raw_function(
    name: str, c_function: str, row: signatures.Function, guest: str, extra: str, returns: str, trapped: bool
) -> str:
    """The text of one raw function of wasm3. The arguments are copied out of the stack of wasm3 first: a call back into the module (the `cabi_realloc` of a result) reuses it."""
    results = len(row.results)
    params = [WIDTH[p.type][0] for p in row.params]
    # the call into fusedwasi is in a function of its own that is not inlined, so that the setjmp of the raw function has nothing of the library in its frame (-Wclobbered)
    inner_parameters = ", ".join(
        ["neutral_inst *in", *[f"{t} a{i}" for i, t in enumerate(params)], *(["int *trapped"] if trapped else [])]
    )
    inner_arguments = ", ".join(
        [guest, *([extra] if extra else []), *[f"a{i}" for i in range(len(params))], *(["trapped"] if trapped else [])]
    )
    lines: list[str] = [
        f"static NEUTRAL_NOINLINE {returns} {name}_call({inner_parameters}) {{",
        f"    {'return ' if returns != 'void' else ''}{c_function}({inner_arguments});",
        "}",
        f"static const void *{name}(IM3Runtime rt, IM3ImportContext ctx, uint64_t *sp, void *mem) {{",
        "    neutral_inst *in = (neutral_inst *)ctx->userdata;",
        "    (void)mem;",
    ]
    for i, ctype in enumerate(params):
        lines.append(f"    {ctype} a{i};")
        lines.append(f"    memcpy(&a{i}, &sp[{results + i}], sizeof a{i});")
    call_arguments = ", ".join(["in", *[f"a{i}" for i in range(len(params))], *(["&trapped"] if trapped else [])])
    if trapped:
        lines.append("    int trapped = 0;")
    if returns != "void":
        lines.append(f"    {returns} r = 0;")
    assignment = "r = " if returns != "void" else ""
    lines.append(f"    NEUTRAL_RUN(in, rt, {assignment}{name}_call({call_arguments}));")
    if trapped:
        lines.append("    if (trapped) return neutral_trapped(in);")
    if returns != "void":
        lines.append("    memcpy(&sp[0], &r, sizeof r);")
    lines.append("    return m3Err_none;")
    lines.append("}")
    return "\n".join(lines)


def signature_text(row: signatures.Function) -> str:
    result = WIDTH[row.results[0].type][1] if row.results else "v"
    return result + "(" + "".join(WIDTH[p.type][1] for p in row.params) + ")"


def main(output: str) -> None:
    out = [
        "/* Generated by gen_wasm3_glue.py from the table of signatures and the headers of fusedwasi. Do not edit. */",
        "#include <fusedwasi/p1/wasi_p1.h>",
        *[f"#include <fusedwasi/p2/wasi_p2_{p}.h>" for p in P2_PACKAGES],
        "",
    ]
    p1_entries: list[str] = []
    for index, row in enumerate(signatures.load("p1").functions):
        returns = "uint32_t" if row.results else "void"
        out.append(raw_function(f"neutral_p1_{index}", f"fusedwasi_p1_{row.name}", row, "&in->g1", "", returns, True))
        p1_entries.append(f'    {{"{row.module}", "{row.name}", "{signature_text(row)}", neutral_p1_{index}}},')
    prototypes = p2_prototypes()
    p2_entries: list[str] = []
    skipped: list[str] = []
    for index, row in enumerate(signatures.load("p2").functions):
        c_function = c_name(row)
        if c_function not in prototypes:
            skipped.append(f"{row.module} {row.name}")
            continue
        returns, count = prototypes[c_function]
        if count not in (len(row.params), len(row.params) + 1):
            raise SystemExit(f"{c_function}: {count} parameters in the header, {len(row.params)} in the table")
        extra = "0" if count == len(row.params) + 1 else ""  # `comp`: the memory of the only component
        out.append(raw_function(f"neutral_p2_{index}", c_function, row, "&in->g2", extra, returns, False))
        module = row.module.split("@")[0]
        p2_entries.append(f'    {{"{module}", "{row.name}", "{signature_text(row)}", neutral_p2_{index}}},')
    out += [
        "",
        "typedef struct { const char *module, *name, *signature; M3RawCall function; } neutral_import;",
        "static const neutral_import neutral_p1_imports[] = {",
        *p1_entries,
        "};",
        "static const neutral_import neutral_p2_imports[] = {",
        *p2_entries,
        "};",
        f"/* not in the headers: {', '.join(skipped)} */",
        "",
    ]
    Path(output).write_text("\n".join(out), encoding="utf-8")


if __name__ == "__main__":
    main(sys.argv[1])
