"""Writes the C glue between wasm3 and the functions of fusedwasi: one wasm3 raw function for each import of WASI 0.1 and 0.2, and the two tables that the driver links from.

    python gen_wasm3_glue.py OUTPUT.h

What it reads is the public table of the signatures (`fusedwasi.signatures`): for every import the module, the name, the flat parameters and results, the C symbol (`c_name`) and whether the
function takes the number of the memory (`takes_comp`). The headers are not read.
"""

from __future__ import annotations

import sys
from pathlib import Path

from fusedwasi import signatures

WIDTH = {"i32": ("uint32_t", "i"), "i64": ("uint64_t", "I")}
P2_PACKAGES = ("cli", "clocks", "filesystem", "http", "io", "random", "sockets")


def raw_function(name: str, c_function: str, row: signatures.Function, guest: str, extra: str, returns: str) -> str:
    """The text of one raw function of wasm3. The arguments are copied out of the stack of wasm3 first: a call back into the module (the `cabi_realloc` of a result) reuses it."""
    results = len(row.results)
    params = [WIDTH[p.type][0] for p in row.params]
    # the call into fusedwasi is in a function of its own that is not inlined, so that the setjmp of the raw function has nothing of the library in its frame (-Wclobbered)
    inner_parameters = ", ".join(["neutral_inst *in", *[f"{t} a{i}" for i, t in enumerate(params)]])
    inner_arguments = ", ".join([guest, *([extra] if extra else []), *[f"a{i}" for i in range(len(params))]])
    lines: list[str] = [
        f"static NEUTRAL_NOINLINE {returns} {name}_call({inner_parameters}) {{",
        f"    {'return ' if returns != 'void' else ''}{c_function}({inner_arguments});",
        "}",
        f"static const void *{name}(IM3Runtime rt, IM3ImportContext ctx, uint64_t *sp, void *mem) {{",
        "    neutral_inst *in = (neutral_inst *)ctx->userdata;",
        "    (void)mem;",
    ]
    for i, ctype in enumerate(params):
        lines.append(f"    {ctype} a{i};")
        lines.append(f"    memcpy(&a{i}, &sp[{results + i}], sizeof a{i});")
    call_arguments = ", ".join(["in", *[f"a{i}" for i in range(len(params))]])
    if returns != "void":
        lines.append(f"    {returns} r = 0;")
    assignment = "r = " if returns != "void" else ""
    lines.append(f"    NEUTRAL_RUN(in, rt, {assignment}{name}_call({call_arguments}));")
    if returns != "void":
        lines.append("    memcpy(&sp[0], &r, sizeof r);")
    lines.append("    return m3Err_none;")
    lines.append("}")
    return "\n".join(lines)


def signature_text(row: signatures.Function) -> str:
    result = WIDTH[row.results[0].type][1] if row.results else "v"
    return result + "(" + "".join(WIDTH[p.type][1] for p in row.params) + ")"


def main(output: str) -> None:
    out = [
        "/* Generated by gen_wasm3_glue.py from the table of signatures of fusedwasi. Do not edit. */",
        "#include <fusedwasi/p1/wasi_p1.h>",
        "#include <fusedwasi/p1/wasi_p1_unstable.h>",
        *[f"#include <fusedwasi/p2/wasi_p2_{p}.h>" for p in P2_PACKAGES],
        "",
    ]
    p1_entries: list[str] = []
    for index, row in enumerate(signatures.load("p1").functions):
        returns = "uint32_t" if row.results else "void"
        assert row.c_name is not None
        out.append(raw_function(f"neutral_p1_{index}", row.c_name, row, "&in->g", "", returns))
        p1_entries.append(f'    {{"{row.module}", "{row.name}", "{signature_text(row)}", neutral_p1_{index}}},')
    unstable_entries: list[str] = []
    for index, row in enumerate(signatures.load("p1").unstable):
        returns = "uint32_t" if row.results else "void"
        assert row.c_name is not None
        out.append(raw_function(f"neutral_unstable_{index}", row.c_name, row, "&in->g", "", returns))
        unstable_entries.append(
            f'    {{"{row.module}", "{row.name}", "{signature_text(row)}", neutral_unstable_{index}}},'
        )
    p2_entries: list[str] = []
    skipped: list[str] = []
    for index, row in enumerate(signatures.load("p2").functions):
        if row.c_name is None:
            skipped.append(f"{row.module} {row.name}")
            continue
        returns = {"i32": "uint32_t", "i64": "uint64_t"}[row.results[0].type] if row.results else "void"
        extra = "0" if row.takes_comp else ""  # `comp`: the memory of the only component
        out.append(raw_function(f"neutral_p2_{index}", row.c_name, row, "&in->g", extra, returns))
        module = row.module.split("@")[0]
        p2_entries.append(f'    {{"{module}", "{row.name}", "{signature_text(row)}", neutral_p2_{index}}},')
    out += [
        "",
        "typedef struct { const char *module, *name, *signature; M3RawCall function; } neutral_import;",
        "static const neutral_import neutral_p1_imports[] = {",
        *p1_entries,
        "};",
        "static const neutral_import neutral_unstable_imports[] = {",
        *unstable_entries,
        "};",
        "static const neutral_import neutral_p2_imports[] = {",
        *p2_entries,
        "};",
        f"/* left out by fusedwasi: {', '.join(skipped)} */",
        "",
    ]
    Path(output).write_text("\n".join(out), encoding="utf-8")


if __name__ == "__main__":
    main(sys.argv[1])
