/* ---- the imports of a module ----------------------------------------------------------------------------------------------- */

static uint32_t leb(const uint8_t **p) {
    uint32_t value = 0;
    int shift = 0;
    for (;;) {
        uint8_t byte = *(*p)++;
        value |= (uint32_t)(byte & 0x7f) << shift;
        if (!(byte & 0x80)) return value;
        shift += 7;
    }
}

static char *name_of(const uint8_t **p) {
    uint32_t n = leb(p);
    char *text = (char *)malloc(n + 1);
    memcpy(text, *p, n);
    text[n] = 0;
    *p += n;
    return text;
}

/* Links the functions of fusedwasi that the module imports, under the names it imports them by. Only the section of the imports is read. The version of a package of WASI 0.2 is
   cut: the table is of one version and the module is of another (the user matches them). Returns the number of imports that have no function. */
static int neutral_link(IM3Module module, const uint8_t *wasm, size_t size, void *userdata) {
    const uint8_t *p = wasm + 8, *end = wasm + size;
    int missing = 0;
    while (p < end) {
        uint8_t id = *p++;
        uint32_t length = leb(&p);
        const uint8_t *next = p + length;
        if (id == 2) {
            uint32_t count = leb(&p);
            for (uint32_t i = 0; i < count; i++) {
                char *mod = name_of(&p), *name = name_of(&p);
                uint8_t kind = *p++;
                if (kind == 0) {
                    leb(&p);
                } else if (kind == 1) {
                    p++;
                    uint32_t flags = leb(&p);
                    leb(&p);
                    if (flags & 1) leb(&p);
                } else if (kind == 2) {
                    uint32_t flags = leb(&p);
                    leb(&p);
                    if (flags & 1) leb(&p);
                } else {
                    p += 2;
                }
                if (kind == 0) {
                    char versionless[256];
                    snprintf(versionless, sizeof versionless, "%s", mod);
                    char *at = strchr(versionless, '@');
                    if (at) *at = 0;
                    const neutral_import *table = neutral_p2_imports;
                    size_t count_in_table = sizeof neutral_p2_imports / sizeof *neutral_p2_imports;
                    if (!strcmp(mod, "wasi_snapshot_preview1")) table = neutral_p1_imports, count_in_table = sizeof neutral_p1_imports / sizeof *neutral_p1_imports;
                    else if (!strcmp(mod, "wasi_unstable")) table = neutral_unstable_imports, count_in_table = sizeof neutral_unstable_imports / sizeof *neutral_unstable_imports;
                    int found = 0;
                    for (size_t k = 0; k < count_in_table; k++) {
                        const char *wanted = table == neutral_p2_imports ? versionless : mod;
                        if (!strcmp(table[k].module, wanted) && !strcmp(table[k].name, name)) {
                            M3Result e = m3_LinkRawFunctionEx(module, mod, name, table[k].signature, table[k].function, userdata);
                            if (e) fprintf(stderr, "link %s %s: %s\n", mod, name, e);
                            found = 1;
                            break;
                        }
                    }
                    if (!found) missing++, fprintf(stderr, "no function for %s %s\n", mod, name);
                }
                free(mod);
                free(name);
            }
        }
        p = next;
    }
    return missing;
}

/* ---- main ------------------------------------------------------------------------------------------------------------------ */

static uint8_t *read_file(const char *path, size_t *size) {
    FILE *f = fopen(path, "rb");
    if (!f) return NULL;
    fseek(f, 0, SEEK_END);
    long n = ftell(f);
    fseek(f, 0, SEEK_SET);
    uint8_t *data = (uint8_t *)malloc((size_t)n);
    if (fread(data, 1, (size_t)n, f) != (size_t)n) return NULL;
    fclose(f);
    *size = (size_t)n;
    return data;
}

int main(int argc, char **argv) {
#ifdef _WIN32
    _setmode(_fileno(stdout), _O_BINARY); /* the bytes of the guest are compared as they are */
#endif
    const char *world = "p1", *entry = NULL;
    const char *args[64], *env_names[64], *env_values[64];
    struct fusedwasi_p2_preopen preopens[8];
    uint32_t arg_count = 0, env_count = 0, preopen_count = 0;
    const char *modules[16];
    int module_count = 0;
    for (int i = 1; i < argc; i++) {
        if (!strcmp(argv[i], "--world") && i + 1 < argc) world = argv[++i];
        else if (!strcmp(argv[i], "--entry") && i + 1 < argc) entry = argv[++i];
        else if (!strcmp(argv[i], "--arg") && i + 1 < argc) args[arg_count++] = argv[++i];
        else if (!strcmp(argv[i], "--env") && i + 1 < argc) {
            char *pair = neutral_copy(argv[++i]);
            char *eq = strchr(pair, '=');
            *eq = 0;
            env_names[env_count] = pair, env_values[env_count++] = eq + 1;
        } else if (!strcmp(argv[i], "--dir") && i + 1 < argc) {
            char *pair = neutral_copy(argv[++i]);
            char *sep = strstr(pair, "::");
            *sep = 0;
            preopens[preopen_count].path = pair, preopens[preopen_count].name = sep + 2, preopens[preopen_count++].writable = 1;
        } else modules[module_count++] = argv[i];
    }
    int p1 = !strcmp(world, "p1");
    if (!entry) entry = p1 ? "_start" : "run";

    /* the world: one for all the instances */
    fusedwasi_p2_state state;
    fusedwasi_p2_init(&state);
    state.args = args, state.arg_count = arg_count;
    state.env_names = env_names, state.env_values = env_values, state.env_count = env_count;
    state.preopens = preopens, state.preopen_count = preopen_count;
    if (p1) {  /* the descriptors of 0.1 are made at the first call; this tells a directory that cannot be opened now */
        int err = 0;
        size_t bad = 0;
        if (fusedwasi_p1_open_descriptors(&state, &err, &bad)) {
            fprintf(stderr, "cannot open the directory %zu: errno %d\n", bad, err);
            return 2;
        }
    }

    /* the instances, all made before the first one runs */
    IM3Environment environment = m3_NewEnvironment();
    neutral_inst *instances[16];
    for (int i = 0; i < module_count; i++) {
        neutral_inst *in = (neutral_inst *)calloc(1, sizeof *in);
        instances[i] = in;
        in->wasm = read_file(modules[i], &in->wasm_size);
        if (!in->wasm) {
            fprintf(stderr, "cannot read %s\n", modules[i]);
            return 2;
        }
        in->rt = m3_NewRuntime(environment, 64 * 1024, in);
        IM3Module module;
        M3Result e = m3_ParseModule(environment, &module, in->wasm, (uint32_t)in->wasm_size);
        if (!e) e = m3_LoadModule(in->rt, module);
        if (e) {
            fprintf(stderr, "%s: %s\n", modules[i], e);
            return 2;
        }
        if (neutral_link(module, in->wasm, in->wasm_size, in)) return 2;
        fusedwasi_p2_guest_init(&in->g, &state);
        in->g.user = in;
        in->g.trap = neutral_trap;
        in->g.realloc = neutral_realloc;
        fusedwasi_p2_bind_memory(&in->g, 0, &in->base, &in->size);
        if (m3_FindFunction(&in->realloc_function, in->rt, "cabi_realloc")) in->realloc_function = NULL;
    }

    /* the calls, one instance after the other, over the one state */
    int status = 0;
    for (int i = 0; i < module_count; i++) {
        neutral_inst *in = instances[i];
        fusedwasi_p2_guest *core = &in->g;
        IM3Function function;
        M3Result e = m3_FindFunction(&function, in->rt, entry);
        if (e) {
            fprintf(stderr, "%s: no export %s: %s\n", modules[i], entry, e);
            return 2;
        }
        core->exited = 0, core->exit_code = 0; /* the host clears the end of the last call */
        in->trap_text[0] = 0;
        neutral_sync(in, in->rt);
        e = m3_Call(function, 0, NULL);
        fflush(stdout);
        const char *trap = (e && !core->exited) ? e : NULL;
        fprintf(stderr, "result %d exited=%d code=%u trap=%s\n", i, core->exited, core->exited ? core->exit_code : 0, trap ? trap : "-");
        if (trap) status = 1;
    }

    fusedwasi_p2_free(&state);
    return status;
}
