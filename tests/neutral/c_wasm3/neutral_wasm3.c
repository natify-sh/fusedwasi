/* strdup is a deprecated name for MSVC */
static char *neutral_copy(const char *text) {
    size_t n = strlen(text) + 1;
    char *copy = (char *)malloc(n);
    if (copy) memcpy(copy, text, n);
    return copy;
}

#if defined(__GNUC__)
#define NEUTRAL_NOINLINE __attribute__((noinline))
#else
#define NEUTRAL_NOINLINE
#endif

/* ---- one instance ---------------------------------------------------------------------------------------------------------- */

typedef struct neutral_inst {
    IM3Runtime rt;
    IM3Function realloc_function; /* the export cabi_realloc, if any */
    uint8_t *base;                /* the cells the guest reads the memory from */
    uint64_t size;
    jmp_buf *jmp; /* the setjmp of the import in progress */
    char trap_text[256];
    fusedwasi_p2_guest g; /* one guest, for a module of 0.1 and for one of 0.2 */
    uint8_t *wasm; /* the bytes of the module: wasm3 keeps pointers into them */
    size_t wasm_size;
} neutral_inst;

static void neutral_sync(neutral_inst *in, IM3Runtime rt) {
    uint32_t size = 0;
    in->base = m3_GetMemory(rt, &size, 0);
    in->size = size;
}

/* Runs the statement of an import under a setjmp; a trap is a longjmp that gets here and returns the text to wasm3. The memory is looked at again first. */
#define NEUTRAL_RUN(in, rt, ...) \
    jmp_buf neutral_jb; \
    jmp_buf *neutral_outer = (in)->jmp; \
    (in)->jmp = &neutral_jb; \
    if (setjmp(neutral_jb)) { \
        (in)->jmp = neutral_outer; \
        return (in)->trap_text; \
    } \
    neutral_sync((in), (rt)); \
    __VA_ARGS__; \
    (in)->jmp = neutral_outer

/* the hook `trap` of the guests: it must not return */
static void neutral_trap(fusedwasi_p2_guest *g, const char *message) {
    neutral_inst *in = (neutral_inst *)g->user;
    snprintf(in->trap_text, sizeof in->trap_text, "%s", message);
    longjmp(*in->jmp, 1);
}

/* the hook `realloc`: the cabi_realloc of the module, called from inside the import that is running */
static uint32_t neutral_realloc(fusedwasi_p2_guest *g, uint32_t comp, uint32_t old_ptr, uint32_t old_size, uint32_t align, uint32_t new_size) {
    neutral_inst *in = (neutral_inst *)g->user;
    uint32_t result = 0;
    const void *arguments[4] = {&old_ptr, &old_size, &align, &new_size};
    const void *results[1] = {&result};
    (void)comp;
    if (!in->realloc_function) return 0;
    if (m3_Call(in->realloc_function, 4, arguments) || m3_GetResults(in->realloc_function, 1, results)) neutral_trap(g, "cabi_realloc trapped");
    neutral_sync(in, in->rt); /* the call may have grown the memory, and moved it */
    return result;
}

